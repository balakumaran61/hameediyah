// Generates src/data/assets.ts from tasks/reference/assets.json (the source of truth).
import { readFileSync, writeFileSync } from 'node:fs'
const d = JSON.parse(readFileSync(new URL('../../tasks/reference/assets.json', import.meta.url), 'utf8'))
const images = Object.fromEntries(d.images.map((i) => [i.id, {
  id: i.id, src: `/img/${i.id}.webp`, alt: i.caption, credit: i.author, license: i.license,
  creditRequired: i.creditRequired, sourcePage: i.sourcePage, usedIn: i.usedIn,
  width: Number(i.originalSize.split('x')[0]), height: Number(i.originalSize.split('x')[1]),
}]))
const videos = Object.fromEntries(d.videos.map((v) => [v.id, {
  id: v.id, youtubeId: v.youtubeId, title: v.title, channel: v.channel, embed: v.embed, poster: v.poster, usedIn: v.usedIn,
}]))
const out = `// GENERATED by scripts/gen-assets.mjs from tasks/reference/assets.json. Do not edit by hand.
export type ImageId = ${Object.keys(images).map((k) => `'${k}'`).join(' | ')}
export type VideoId = ${Object.keys(videos).map((k) => `'${k}'`).join(' | ')}
export interface ImageAsset { id: ImageId; src: string; alt: string; credit: string; license: string; creditRequired: boolean; sourcePage: string; usedIn: string; width: number; height: number }
export interface VideoAsset { id: VideoId; youtubeId: string; title: string; channel: string; embed: string; poster: string; usedIn: string }
export const images: Record<ImageId, ImageAsset> = ${JSON.stringify(images, null, 2)}
export const videos: Record<VideoId, VideoAsset> = ${JSON.stringify(videos, null, 2)}
`
writeFileSync(new URL('../src/data/assets.ts', import.meta.url), out)
console.log('assets.ts written:', d.images.length, 'images,', d.videos.length, 'videos')
