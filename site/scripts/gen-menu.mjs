// Generates src/data/menu.ts from docs/MENU-DATA.md. Edit the doc, then re-run: npm run gen:menu
import { readFileSync, writeFileSync } from 'node:fs'
const md = readFileSync(new URL('../../docs/MENU-DATA.md', import.meta.url), 'utf8')
const rows = md.split('\n').filter((l) => /^\| [a-z0-9-]+ \|/.test(l) && !l.startsWith('| slug'))
// keep [VERIFY: note] text in the story: the UI renders it as a visible marker
const strip = (s) => s.replace(/`/g, '').replace(/\s+/g, ' ').trim()
const dishes = rows.map((l) => {
  const c = l.split('|').slice(1, -1).map((s) => s.trim())
  const [slug, en, ms, tray, protein, heat, sig, story, pairs, price, source] = c
  const v = [...l.matchAll(/\[VERIFY:?\s*([^\]]*)\]/g)].map((m) => m[1].trim() || 'to be verified')
  return {
    slug, en, ms, tray, protein: protein.split('/').map((p) => p.trim()), heat: Number(heat), signature: sig === 'y',
    story: strip(story), pairs: pairs.split(',').map((p) => p.trim()), price, source, verify: v,
  }
})
const out = `// GENERATED by scripts/gen-menu.mjs from docs/MENU-DATA.md. Do not edit by hand.
export type TrayId = 'nasi' | 'kuah' | 'roti' | 'goreng' | 'laut' | 'minum'
export interface Dish { slug: string; en: string; ms: string; tray: TrayId; protein: string[]; heat: 1 | 2 | 3 | 4 | 5; signature: boolean; story: string; pairs: string[]; price: string; source: string; verify: string[] }
export const TRAYS: { id: TrayId; label: string }[] = [
  { id: 'nasi', label: 'Nasi & Rice' }, { id: 'kuah', label: 'Curries (Kuah)' }, { id: 'roti', label: 'Murtabak & Roti' },
  { id: 'goreng', label: 'Fried (Goreng)' }, { id: 'laut', label: 'Seafood' }, { id: 'minum', label: 'Drinks' },
]
export const DISHES: Dish[] = ${JSON.stringify(dishes, null, 2)} as Dish[]
`
writeFileSync(new URL('../src/data/menu.ts', import.meta.url), out)
console.log('menu.ts:', dishes.length, 'dishes')
